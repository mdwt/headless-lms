import { z } from 'zod';
import {
  AssignmentList,
  ContentIdParam,
  CreateInvite,
  CreateRole,
  Invite,
  MembersPage,
  MembersQuery,
  OrgRoleList,
  OrgRoleView,
  OrgUserContentParam,
  OrgUserIdParam,
  Organization,
  OrganizationHosts,
  ReplaceOrganizationHosts,
  ResendInvite,
  RoleKeyParam,
  SetRole,
  UpdateOrganization,
  UpdateRole,
} from '../../schemas/index.js';
import { defineTool, noInput, type Tool } from '../tool.js';

export const organizationTools: Tool[] = [
  defineTool({
    name: 'update_organization',
    title: 'Update organization',
    description: "Change the organization's name or slug.",
    kind: 'write',
    idempotent: true,
    openWorld: false,
    input: UpdateOrganization,
    output: Organization,
    call: async (input, { container, caller }) => {
      const org = await container.organizations.updateOrganization(input, caller.actor);
      return { id: org.id, name: org.name, slug: org.slug, createdAt: org.createdAt.toISOString() };
    },
  }),
  defineTool({
    name: 'get_organization_hosts',
    title: 'Get organization hosts',
    description:
      "The origins of the organization's member apps, used for the links in emails, invites and calendar files.",
    kind: 'read',
    idempotent: true,
    openWorld: false,
    input: noInput,
    output: OrganizationHosts,
    call: (_input, { container, caller }) => container.hosts.get(caller.actor),
  }),
  defineTool({
    name: 'replace_organization_hosts',
    title: 'Replace organization hosts',
    description: 'Set the course host and the community host. The next link uses the new value.',
    kind: 'write',
    idempotent: true,
    openWorld: false,
    input: ReplaceOrganizationHosts,
    output: OrganizationHosts,
    call: (input, { container, caller }) => container.hosts.replace(input, caller.actor),
  }),
  defineTool({
    name: 'list_roles',
    title: 'List roles',
    description:
      "The organization's roles with their levels, permissions and how many people hold each.",
    kind: 'read',
    idempotent: true,
    openWorld: false,
    input: noInput,
    output: z.object({ roles: OrgRoleList }),
    call: async (_input, { container, caller }) => ({
      roles: await container.organizations.listRoles(caller.actor),
    }),
  }),
  defineTool({
    name: 'get_role',
    title: 'Get role',
    description: 'One role with its levels and permissions.',
    kind: 'read',
    idempotent: true,
    openWorld: false,
    input: RoleKeyParam,
    output: OrgRoleView,
    call: ({ key }, { container, caller }) => container.organizations.getRole(key, caller.actor),
  }),
  defineTool({
    name: 'update_role',
    title: 'Update role',
    description:
      'Rename a role, or change its permissions, levels or team flag. Changes need every permission the role holds before and after.',
    kind: 'write',
    idempotent: true,
    openWorld: false,
    input: UpdateRole.extend(RoleKeyParam.shape),
    output: OrgRoleView,
    call: ({ key, ...input }, { container, caller }) =>
      container.organizations.updateRole(key, input, caller.actor),
  }),
  defineTool({
    name: 'create_role',
    title: 'Create role',
    description: 'Add a role to the organization, starting from a deployment role (base).',
    kind: 'write',
    idempotent: false,
    openWorld: false,
    input: CreateRole,
    output: OrgRoleView,
    call: (input, { container, caller }) => container.organizations.createRole(input, caller.actor),
  }),
  defineTool({
    name: 'reset_role',
    title: 'Reset role',
    description: "Reset a deployment role to the deployment's version.",
    kind: 'destructive',
    idempotent: true,
    openWorld: false,
    input: RoleKeyParam,
    output: OrgRoleView,
    call: ({ key }, { container, caller }) => container.organizations.resetRole(key, caller.actor),
  }),
  defineTool({
    name: 'delete_role',
    title: 'Delete role',
    description: 'Delete a role the organization added. Refused while anyone holds it.',
    kind: 'destructive',
    idempotent: false,
    openWorld: false,
    input: RoleKeyParam,
    call: ({ key }, { container, caller }) => container.organizations.deleteRole(key, caller.actor),
  }),
  defineTool({
    name: 'list_team',
    title: 'List team',
    description:
      'Everyone with an org role other than Member or a role on a content item, invited people included.',
    kind: 'read',
    idempotent: true,
    openWorld: false,
    input: MembersQuery,
    output: MembersPage,
    call: (input, { container, caller }) => container.organizations.listTeam(input, caller.actor),
  }),
  defineTool({
    name: 'list_person_roles',
    title: "List a person's roles",
    description: "A person's org role and every role they hold on a content item.",
    kind: 'read',
    idempotent: true,
    openWorld: false,
    input: OrgUserIdParam,
    output: z.object({ roles: AssignmentList }),
    call: async ({ orgUserId }, { container, caller }) => ({
      roles: await container.organizations.listAssignments(orgUserId, caller.actor),
    }),
  }),
  defineTool({
    name: 'list_roles_on_content',
    title: 'List roles on content',
    description: 'The people with a role on one course, download, community or event.',
    kind: 'read',
    idempotent: true,
    openWorld: false,
    input: ContentIdParam,
    output: z.object({ roles: AssignmentList }),
    call: async ({ contentId }, { container, caller }) => ({
      roles: await container.organizations.listAssignmentsOn(contentId, caller.actor),
    }),
  }),
  defineTool({
    name: 'set_org_role',
    title: 'Set org role',
    description: "Set a person's org role. Needs every permission the old and the new role hold.",
    kind: 'write',
    idempotent: true,
    openWorld: false,
    input: SetRole.extend(OrgUserIdParam.shape),
    output: z.object({ roles: AssignmentList }),
    call: async ({ orgUserId, roleKey }, { container, caller }) => ({
      roles: await container.organizations.setOrgRole(orgUserId, roleKey, caller.actor),
    }),
  }),
  defineTool({
    name: 'assign_role',
    title: 'Give a role on content',
    description:
      "Give a person a role on one course, download, community or event. The role must list the item's type.",
    kind: 'write',
    idempotent: true,
    openWorld: false,
    input: SetRole.extend(OrgUserContentParam.shape),
    output: z.object({ roles: AssignmentList }),
    call: async ({ orgUserId, contentId, roleKey }, { container, caller }) => ({
      roles: await container.organizations.assignRole(orgUserId, contentId, roleKey, caller.actor),
    }),
  }),
  defineTool({
    name: 'unassign_role',
    title: 'Remove a role on content',
    description: "Remove a person's role on one course, download, community or event.",
    kind: 'destructive',
    idempotent: true,
    openWorld: false,
    input: OrgUserContentParam,
    output: z.object({ roles: AssignmentList }),
    call: async ({ orgUserId, contentId }, { container, caller }) => ({
      roles: await container.organizations.unassignRole(orgUserId, contentId, caller.actor),
    }),
  }),
  defineTool({
    name: 'invite_person',
    title: 'Invite person',
    description:
      'Invite someone by email with an org role (default member). They exist as an invited person at once.',
    kind: 'write',
    idempotent: false,
    openWorld: true,
    input: CreateInvite,
    output: Invite,
    call: async (input, { container, caller }) => {
      const invite = await container.organizations.createInvite(input, caller.actor, caller.userId);
      return {
        id: invite.id,
        orgUserId: invite.orgUserId,
        email: invite.email,
        roleKey: invite.roleKey,
        status: invite.status,
        expiresAt: invite.expiresAt,
        createdAt: invite.createdAt,
      };
    },
  }),
  defineTool({
    name: 'resend_invite',
    title: 'Resend invite',
    description: "Send a person's pending invite email again, with a new link.",
    kind: 'write',
    idempotent: false,
    openWorld: true,
    input: OrgUserIdParam.extend(ResendInvite.shape),
    call: ({ orgUserId, host }, { container, caller }) =>
      container.organizations.resendInvite(orgUserId, caller.actor, caller.userId, host),
  }),
  defineTool({
    name: 'cancel_invite',
    title: 'Cancel invite',
    description: "Cancel a person's pending invite.",
    kind: 'destructive',
    idempotent: false,
    openWorld: false,
    input: OrgUserIdParam,
    call: ({ orgUserId }, { container, caller }) =>
      container.organizations.cancelInvite(orgUserId, caller.actor),
  }),
  defineTool({
    name: 'remove_person',
    title: 'Remove person',
    description:
      'Remove a person from the organization, with their API keys and connected apps here. Needs every permission they hold.',
    kind: 'destructive',
    idempotent: false,
    openWorld: false,
    input: OrgUserIdParam,
    call: ({ orgUserId }, { container, caller }) =>
      container.organizations.removePerson(orgUserId, caller.actor),
  }),
];
